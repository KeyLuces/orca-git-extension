// Packs the Git Graph page into one self-contained HTML file (panel/graph.html).
// Orca's web client (orca serve in a browser, e.g. on a phone) loads a plugin frame as a single
// sandboxed document that cannot fetch sibling files, so the styles and script are inlined here.
// The desktop app loads the same file. Run after editing panel/tab.html, style.css or app.js:
//   node tools/build.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const panel = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'panel')
const read = (f) => readFileSync(path.join(panel, f), 'utf8')

let html = read('tab.html')
const css = read('style.css')
// "</script" inside the script would end the inline element early
const js = read('app.js').replace(/<\/script/gi, '<\\/script')

const linkTag = /<link rel="stylesheet" href="style\.css"\s*\/?>/
const scriptTag = /<script type="module" src="app\.js"><\/script>/
if (!linkTag.test(html) || !scriptTag.test(html)) throw new Error('tab.html no longer has the expected style/script tags')
html = html.replace(linkTag, () => `<style>\n${css}\n</style>`).replace(scriptTag, () => `<script type="module">\n${js}\n</script>`)
html = html.replace('<head>', '<head>\n    <!-- Generated by tools/build.mjs from tab.html, style.css and app.js. Do not edit. -->')
writeFileSync(path.join(panel, 'graph.html'), html)
console.log(`panel/graph.html: ${(html.length / 1024).toFixed(0)} KB`)
